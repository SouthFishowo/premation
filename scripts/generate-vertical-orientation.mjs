#!/usr/bin/env node
/**
 * Generate src/core/text/verticalOrientationData.ts from the Unicode
 * Character Database's VerticalOrientation.txt (UAX #50).
 *
 *   node scripts/generate-vertical-orientation.mjs            # fetch latest
 *   node scripts/generate-vertical-orientation.mjs --input VerticalOrientation.txt
 *
 * The property is range-compressed: every code point from 0 to U+10FFFF gets
 * a value (the file's header rules: unassigned code points in the listed
 * blocks default to U, everything else not listed to R), then consecutive
 * code points with the same value collapse to one range start.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const URL_LATEST = 'https://www.unicode.org/Public/UCD/latest/ucd/VerticalOrientation.txt';
const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/core/text/verticalOrientationData.ts');

const CODE = { R: 'R', U: 'U', Tu: 'u', Tr: 'r' };

async function source() {
  const i = process.argv.indexOf('--input');
  if (i >= 0 && process.argv[i + 1]) return readFileSync(process.argv[i + 1], 'utf8');
  const res = await fetch(URL_LATEST);
  if (!res.ok) throw new Error(`fetch ${URL_LATEST}: ${res.status}`);
  return res.text();
}

const text = await source();
const lines = text.split(/\r?\n/);
const version = /VerticalOrientation-(\d+\.\d+\.\d+)\.txt/.exec(lines[0] ?? '')?.[1];
const date = /Date:\s*(\d{4}-\d{2}-\d{2})/.exec(lines[1] ?? '')?.[1] ?? '';
if (!version) throw new Error('No version header in VerticalOrientation.txt');

const vo = new Uint8Array(0x110000).fill(CODE.R.charCodeAt(0));
const set = (a, b, v) => vo.fill(v.charCodeAt(0), a, b + 1);

// Header: "all unassigned code points default to U" blocks.
let inDefaults = false;
for (const line of lines) {
  if (!line.startsWith('#')) break;
  if (/unassigned code points default to U/.test(line)) inDefaults = true;
  else if (/All other code points/.test(line)) inDefaults = false;
  if (!inDefaults) continue;
  const m = /U\+([0-9A-F]{4,6})(?:\.\.U\+([0-9A-F]{4,6}))?\s*$/.exec(line);
  if (m) set(parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16), CODE.U);
}

let entries = 0;
for (const line of lines) {
  const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(U|R|Tu|Tr)\b/.exec(line);
  if (!m) continue;
  set(parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16), CODE[m[3]]);
  entries++;
}
if (entries < 100) throw new Error(`Only ${entries} entries parsed`);

const starts = [];
let values = '';
for (let cp = 0; cp < vo.length; cp++) {
  if (cp === 0 || vo[cp] !== vo[cp - 1]) {
    starts.push(cp);
    values += String.fromCharCode(vo[cp]);
  }
}

const hex = (n) => `0x${n.toString(16)}`;
const rows = [];
for (let i = 0; i < starts.length; i += 12) rows.push(`  ${starts.slice(i, i + 12).map(hex).join(', ')},`);
const valueRows = [];
for (let i = 0; i < values.length; i += 96) valueRows.push(`  '${values.slice(i, i + 96)}'`);

const out = `/**
 * GENERATED by scripts/generate-vertical-orientation.mjs — do not edit.
 *
 * Unicode ${version} Vertical_Orientation (UAX #50), from
 * VerticalOrientation-${version}.txt (${date}).
 *
 * Range-compressed: \`VO_RANGE_STARTS[i]\` is the first code point of a range
 * that runs up to the next start; \`VO_RANGE_VALUES[i]\` is its value —
 * U upright, R rotated, u = Tu (transformed, fallback upright),
 * r = Tr (transformed, fallback rotated).
 */

export const VERTICAL_ORIENTATION_UNICODE_VERSION = '${version}';

export const VO_RANGE_STARTS: ReadonlyArray<number> = [
${rows.join('\n')}
];

export const VO_RANGE_VALUES =
${valueRows.join(' +\n')};
`;

writeFileSync(OUT, out);
console.log(`verticalOrientationData.ts: Unicode ${version}, ${entries} entries → ${starts.length} ranges`);
